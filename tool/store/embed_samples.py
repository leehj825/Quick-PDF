"""Embeds the sample documents into integration_test/sample_data.dart (used only by the
real-device screenshot run, so no files have to be pushed onto the emulator).
Usage: python3 tool/store/embed_samples.py [samples_dir]"""
import base64, glob, io, os, sys
from PIL import Image

src = sys.argv[1] if len(sys.argv) > 1 else 'build/store/samples'
entries = []
for f in sorted(glob.glob(f'{src}/*_photo.jpg')):   # phone-photo look only (keeps the file small)
    im = Image.open(f).convert('RGB')
    im.thumbnail((900, 1200))
    buf = io.BytesIO(); im.save(buf, 'JPEG', quality=82)
    entries.append((os.path.splitext(os.path.basename(f))[0], base64.b64encode(buf.getvalue()).decode()))
with open('integration_test/sample_data.dart', 'w') as out:
    out.write('// GENERATED by tool/store/embed_samples.py - do not edit.\nconst Map<String, String> sampleJpegsBase64 = {\n')
    for name, b64 in entries:
        out.write(f"  '{name}': '{b64}',\n")
    out.write('};\n')
print('embedded', len(entries), 'samples,', sum(len(b) for _, b in entries) // 1024, 'KB base64')
